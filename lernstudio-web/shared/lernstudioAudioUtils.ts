// Web Audio API Synthesizer & Voice Feedback for Glück Lernstudio (100% Offline)

let audioCtx: AudioContext | null = null;
let soundMuted = false;

if (typeof window !== 'undefined') {
  try {
    soundMuted = localStorage.getItem('gluck_sound_muted') === 'true';
  } catch {
    soundMuted = false;
  }
}

export function isSoundMuted(): boolean {
  return soundMuted;
}

export function setSoundMuted(muted: boolean): void {
  soundMuted = muted;
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem('gluck_sound_muted', muted ? 'true' : 'false');
    } catch {}
  }
}

function getAudioContext(): AudioContext | null {
  if (typeof window === 'undefined') return null;
  if (!audioCtx) {
    const AudioContextClass = window.AudioContext || (window as any).webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === 'suspended') {
    audioCtx.resume().catch(() => {});
  }
  return audioCtx;
}

// Proactive user-gesture unlock for mobile & desktop autoplay restrictions
if (typeof window !== 'undefined') {
  const unlockAudio = () => {
    try {
      const ctx = getAudioContext();
      if (ctx && ctx.state === 'suspended') {
        ctx.resume().catch(() => {});
      }
    } catch {}
    window.removeEventListener('pointerdown', unlockAudio);
    window.removeEventListener('touchstart', unlockAudio);
    window.removeEventListener('keydown', unlockAudio);
  };
  window.addEventListener('pointerdown', unlockAudio, { passive: true });
  window.addEventListener('touchstart', unlockAudio, { passive: true });
  window.addEventListener('keydown', unlockAudio, { passive: true });
}

