export type GermanVoicePhrase =
  | 'richtig'
  | 'super'
  | 'fantastisch'
  | 'sehr_gut'
  | 'weiter_so'
  | 'geschafft'
  | 'gewonnen'
  | 'noch_einmal'
  | 'correct'
  | 'wrong'
  | 'try_again'
  | 'combo'
  | 'victory';

const germanPhrases: Record<GermanVoicePhrase, string> = {
  richtig: 'Super!',
  super: 'Super!',
  fantastisch: 'Fantastisch!',
  sehr_gut: 'Sehr gut!',
  weiter_so: 'Weiter so!',
  geschafft: 'Geschafft!',
  gewonnen: 'Du hast gewonnen!',
  noch_einmal: 'Versuch es noch einmal!',
  correct: 'Super!',
  wrong: 'Versuch es noch einmal!',
  try_again: 'Versuch es noch einmal!',
  combo: 'Fantastisch! Weiter so!',
  victory: 'Du hast gewonnen!'
};

import { speakGermanText, speakGermanTextAndWait } from './audioSpeechUtils';

export function playGermanVoiceFeedback(phraseKey: GermanVoicePhrase) {
  if (soundMuted) return;
  const phraseText = germanPhrases[phraseKey] || 'Super!';
  speakGermanText(phraseText, 0.85);
}

export function playGermanVoiceFeedbackAndWait(phraseKey: GermanVoicePhrase): Promise<void> {
  if (soundMuted) return Promise.resolve();
  const phraseText = germanPhrases[phraseKey] || 'Super!';
  return speakGermanTextAndWait(phraseText, 0.85);
}
