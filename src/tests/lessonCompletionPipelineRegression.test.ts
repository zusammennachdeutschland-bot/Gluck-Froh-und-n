import assert from 'node:assert/strict';
import { performance } from 'node:perf_hooks';
import type { Lesson } from '../types';
import {
  applyLessonCompletionMutation,
  deduplicateLessonList,
  resequenceScheduledLessonsAfterChange
} from '../utils/lessonUtils';

const makeLesson = (id: string, studentName: string, time: string, status: 'scheduled' | 'completed', groupId?: string): Lesson => ({
  id,
  studentName,
  groupId,
  date: '2026-11-21',
  time,
  durationMinutes: 60,
  status,
  sessionNumber: 1,
  totalSessionsInPackage: 4,
  updatedAt: status === 'completed' ? 2 : 1
} as Lesson);

const assertCompleted = (lessons: Lesson[], boundary: string) => {
  const byId = new Map(lessons.map(lesson => [lesson.id, lesson]));
  for (const id of ['judy-0800', 'kinda-0900', 'taleen-1000']) {
    assert.equal(byId.get(id)?.status, 'completed', `${boundary}: ${id} must be completed`);
  }
  assert.equal(byId.size, 3, `${boundary}: all three IDs must exist exactly once`);
};

const runSameDayHandlerRegression = () => {
  let full: Lesson[] = [
    makeLesson('judy-0800', 'Judy', '08:00', 'completed', 'judy-private'),
    makeLesson('kinda-0900', 'Kinda und Judy', '09:00', 'scheduled', 'kinda-group'),
    makeLesson('taleen-1000', 'Taleen Private', '10:00', 'scheduled', 'taleen-private')
  ];

  // This is the same mutation helper called by AppContext.saveLessonReport from
  // the Home checkmark handler. Invoke it twice, as the teacher does on Home.
  const invokeActualCompletionMutation = (lessonId: string) => {
    const result = applyLessonCompletionMutation(full, lessonId, lesson => ({
      ...lesson,
      status: 'completed',
      isAutoGenerated: false,
      report: { ...(lesson.report || {}), attendanceStatus: 'present' } as any,
      updatedAt: Date.now()
    } as Lesson));
    full = result.lessons;
    assert.equal(result.found, true, `handler must find ${lessonId}`);
    assertCompleted(full, `after ${lessonId} completion mutation`);

    const pivot = full.find(lesson => lesson.id === lessonId)!;
    full = resequenceScheduledLessonsAfterChange(full, pivot);
    assertCompleted(full, `after ${lessonId} resequence`);

    const deduped = deduplicateLessonList(full);
    assert.deepEqual(Array.from(deduped.removedIds), [], 'the three separate lessons must not be deduplicated');
    full = deduped.deduplicated as Lesson[];
    assertCompleted(full, `after ${lessonId} deduplication`);
  };

  invokeActualCompletionMutation('kinda-0900');
  invokeActualCompletionMutation('taleen-1000');
  assertCompleted(full, 'after both Home checkmark handler invocations');
};

const runScaleTests = () => {
  const dedupRows: Lesson[] = Array.from({ length: 5000 }, (_, index) => makeLesson(
    `scale-${index}`,
    `Student ${index}`,
    `${String(Math.floor(index / 60) % 24).padStart(2, '0')}:${String(index % 60).padStart(2, '0')}`,
    'scheduled',
    `group-${index}`
  ));
  const dedupStart = performance.now();
  const deduped = deduplicateLessonList(dedupRows);
  const dedupMs = performance.now() - dedupStart;
  assert.equal(deduped.deduplicated.length, 5000);
  assert.equal(deduped.removedIds.size, 0);
  assert.ok(dedupMs < 3000, `5,000-row indexed deduplication took ${dedupMs.toFixed(1)}ms (limit 3,000ms)`);

  const sequenceRows: Lesson[] = Array.from({ length: 2500 }, (_, index) => ({
    ...makeLesson(`sequence-${index}`, 'Shared Group Student', '08:00', 'scheduled', 'scale-group'),
    date: new Date(Date.UTC(2020, 0, 1 + index)).toISOString().slice(0, 10)
  }));
  const group = { id: 'scale-group', name: 'Scale Group', sessionCount: 4, startingSessionNumber: 1 } as any;
  const resequenceStart = performance.now();
  const resequenced = resequenceScheduledLessonsAfterChange(sequenceRows, sequenceRows[0], { group });
  const resequenceMs = performance.now() - resequenceStart;
  assert.equal(resequenced.length, 2500);
  assert.ok(resequenceMs < 2000, `2,500-row one-pass resequencing took ${resequenceMs.toFixed(1)}ms (limit 2,000ms)`);

  console.log(`✓ Lesson scale tests passed: dedup 5,000 rows ${dedupMs.toFixed(1)}ms; resequence 2,500 rows ${resequenceMs.toFixed(1)}ms.`);
};

runSameDayHandlerRegression();
runScaleTests();
