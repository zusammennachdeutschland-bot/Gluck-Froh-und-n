import assert from 'node:assert/strict';
import { performance } from 'node:perf_hooks';
import type { Lesson, LessonReport } from '../types';
import { storage, __setSimulatePrimaryDbForTests } from '../services/storageService';
import { enqueueLessonSyncTask, waitForLessonSyncQueue } from '../services/lessonSyncQueue';
import { preserveCompletedLessonStatuses } from '../utils/lessonSync';
import { handleHomeQuickLessonCompletion } from '../utils/homeLessonCompletion';
import {
  applyLessonCompletionMutation,
  deduplicateLessonList,
  resequenceScheduledLessonsAfterChange
} from '../utils/lessonUtils';

const makeLesson = (id: string, studentName: string, time: string, status: 'scheduled' | 'completed', groupId?: string): Lesson => ({
  id,
  studentName,
  groupId,
  date: '2026-11-21',
  time,
  durationMinutes: 60,
  status,
  sessionNumber: 1,
  totalSessionsInPackage: 4,
  updatedAt: status === 'completed' ? 2 : 1
} as Lesson);

const assertStatuses = (lessons: Lesson[], expected: Record<string, string>, boundary: string) => {
  const byId = new Map(lessons.map(lesson => [lesson.id, lesson]));
  assert.deepEqual(Array.from(byId.keys()).sort(), Object.keys(expected).sort(), `${boundary}: all IDs must exist exactly once`);
  for (const [id, status] of Object.entries(expected)) {
    assert.equal(byId.get(id)?.status, status, `${boundary}: ${id} must remain ${status}`);
  }
};

const runSameDayHandlerRegression = async () => {
  __setSimulatePrimaryDbForTests(true);
  try {
    let full: Lesson[] = [
      makeLesson('judy-0800', 'Judy', '08:00', 'completed', 'judy-private'),
      makeLesson('kinda-0900', 'Kinda und Judy', '09:00', 'scheduled', 'kinda-group'),
      makeLesson('taleen-1000', 'Taleen Private', '10:00', 'scheduled', 'taleen-private')
    ];
    const staleHomeSnapshot = full.map(lesson => ({ ...lesson }));
    const expectedAfterKinda = { 'judy-0800': 'completed', 'kinda-0900': 'completed', 'taleen-1000': 'scheduled' };
    const expectedAfterTaleen = { 'judy-0800': 'completed', 'kinda-0900': 'completed', 'taleen-1000': 'completed' };
    const pendingWrites: Promise<void>[] = [];

    await storage.setItem('dl_lessons', full);
    await waitForLessonSyncQueue();

    const saveLessonReport = (
      lessonId: string,
      report: LessonReport,
      _packageCount?: number,
      _sessionNumber?: number,
      fallbackLesson?: Lesson
    ) => {
      const expected = lessonId === 'kinda-0900' ? expectedAfterKinda : expectedAfterTaleen;
      const write = enqueueLessonSyncTask(async () => {
        const mutation = applyLessonCompletionMutation(full, lessonId, lesson => ({
          ...lesson,
          status: 'completed',
          isAutoGenerated: false,
          report,
          updatedAt: Date.now()
        } as Lesson), fallbackLesson);
        assert.equal(mutation.found, true, `actual Home handler must find ${lessonId}`);
        full = mutation.lessons;
        assertStatuses(full, expected, `${lessonId}: after actual saveLessonReport mutation`);

        const pivot = full.find(lesson => lesson.id === lessonId)!;
        full = resequenceScheduledLessonsAfterChange(full, pivot);
        assertStatuses(full, expected, `${lessonId}: after actual resequence stage`);

        // Reproduce a delayed stale Home projection arriving at the persistence boundary.
        const guarded = preserveCompletedLessonStatuses([full], staleHomeSnapshot);
        full = guarded.lessons;
        assertStatuses(full, expected, `${lessonId}: after completed-status guard`);

        const deduped = deduplicateLessonList(full);
        assert.deepEqual(Array.from(deduped.removedIds), [], 'the three different lesson slots must not merge');
        full = deduped.deduplicated as Lesson[];
        assertStatuses(full, expected, `${lessonId}: after deduplicateLessonList`);

        await storage.setItem('dl_lessons', full);
        const persisted = (await storage.getItem<Lesson[]>('dl_lessons')) || [];
        assertStatuses(persisted, expected, `${lessonId}: persisted dl_lessons`);
        const reloaded = (await storage.getItem<Lesson[]>('dl_lessons')) || [];
        assertStatuses(reloaded, expected, `${lessonId}: after app reload`);
      });
      pendingWrites.push(write);
    };

    const dependencies = {
      groups: [],
      students: [],
      language: 'en' as const,
      getFullLessonsSnapshot: () => full,
      saveLessonReport,
      clearDraft: (_lessonId: string) => {}
    };

    // Invoke the exact production Home checkmark handler twice, not a reimplementation.
    handleHomeQuickLessonCompletion({ stopPropagation() {} }, full.find(lesson => lesson.id === 'kinda-0900')!, dependencies);
    await pendingWrites.shift();
    await waitForLessonSyncQueue();
    assertStatuses(full, expectedAfterKinda, 'after first real Home checkmark invocation');

    handleHomeQuickLessonCompletion({ stopPropagation() {} }, full.find(lesson => lesson.id === 'taleen-1000')!, dependencies);
    await pendingWrites.shift();
    await waitForLessonSyncQueue();
    assertStatuses(full, expectedAfterTaleen, 'after second real Home checkmark invocation');
  } finally {
    __setSimulatePrimaryDbForTests(false);
  }
};

const runScaleTests = () => {
  const dedupRows: Lesson[] = Array.from({ length: 5000 }, (_, index) => makeLesson(
    `scale-${index}`,
    `Student ${index}`,
    `${String(Math.floor(index / 60) % 24).padStart(2, '0')}:${String(index % 60).padStart(2, '0')}`,
    'scheduled',
    `group-${index}`
  ));
  const dedupStart = performance.now();
  const deduped = deduplicateLessonList(dedupRows);
  const dedupMs = performance.now() - dedupStart;
  assert.equal(deduped.deduplicated.length, 5000);
  assert.equal(deduped.removedIds.size, 0);
  assert.ok(dedupMs < 3000, `5,000-row indexed deduplication took ${dedupMs.toFixed(1)}ms (limit 3,000ms)`);

  const sequenceRows: Lesson[] = Array.from({ length: 2500 }, (_, index) => ({
    ...makeLesson(`sequence-${index}`, 'Shared Group Student', '08:00', 'scheduled', 'scale-group'),
    date: new Date(Date.UTC(2020, 0, 1 + index)).toISOString().slice(0, 10)
  }));
  const group = { id: 'scale-group', name: 'Scale Group', sessionCount: 4, startingSessionNumber: 1 } as any;
  const resequenceStart = performance.now();
  const resequenced = resequenceScheduledLessonsAfterChange(sequenceRows, sequenceRows[0], { group });
  const resequenceMs = performance.now() - resequenceStart;
  assert.equal(resequenced.length, 2500);
  assert.ok(resequenceMs < 2000, `2,500-row one-pass resequencing took ${resequenceMs.toFixed(1)}ms (limit 2,000ms)`);

  console.log(`✓ Lesson scale tests passed: dedup 5,000 rows ${dedupMs.toFixed(1)}ms; resequence 2,500 rows ${resequenceMs.toFixed(1)}ms.`);
};

await runSameDayHandlerRegression();
runScaleTests();
