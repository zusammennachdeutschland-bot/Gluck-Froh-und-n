import assert from 'node:assert/strict';
import type { Lesson } from '../types';
import { storage, __setSimulatePrimaryDbForTests } from '../services/storageService';
import { enqueueLessonSyncTask, waitForLessonSyncQueue } from '../services/lessonSyncQueue';
import { mergeLessonSyncSnapshot, preserveCompletedLessonStatuses } from '../utils/lessonSync';
import { applyLessonCompletionMutation, deduplicateLessonList, resequenceScheduledLessonsAfterChange } from '../utils/lessonUtils';

const makeLesson = (
  id: string,
  studentName: string,
  time: string,
  status: 'scheduled' | 'completed'
): Lesson => ({
  id,
  studentName,
  date: '2026-11-21',
  time,
  status,
  updatedAt: status === 'completed' ? 2 : 1,
} as Lesson);

const assertStatuses = (lessons: Lesson[], expected: Record<string, string>, boundary: string) => {
  assert.deepEqual(
    lessons.map(lesson => lesson.id).sort(),
    Object.keys(expected).sort(),
    `${boundary}: all three lesson IDs must exist exactly once`
  );
  for (const [id, status] of Object.entries(expected)) {
    assert.equal(lessons.find(lesson => lesson.id === id)?.status, status, `${boundary}: ${id} must remain ${status}`);
  }
};

const run = async () => {
  __setSimulatePrimaryDbForTests(true);
  const originalLocalStorage = (globalThis as any).localStorage;
  const localMirror = new Map<string, string>();
  (globalThis as any).localStorage = {
    getItem: (key: string) => localMirror.has(key) ? localMirror.get(key)! : null,
    setItem: (key: string, value: string) => { localMirror.set(key, value); },
    removeItem: (key: string) => { localMirror.delete(key); }
  };
  try {
    // Reproduce restart with an older IndexedDB snapshot and a newer localStorage
    // fallback snapshot after a primary write failure.
    const stalePrimary = makeLesson('restart-status', 'Restart Status', '11:00', 'scheduled');
    const newerMirror = {
      ...makeLesson('restart-status', 'Restart Status', '11:00', 'completed'),
      updatedAt: 2000,
      report: { attendanceStatus: 'present', teacherNotes: 'Saved to fallback mirror' }
    } as Lesson;
    await storage.setItem('dl_lessons', [stalePrimary]);
    localMirror.set('dl_lessons', JSON.stringify([newerMirror]));
    const afterRestart = (await storage.getItem<Lesson[]>('dl_lessons')) || [];
    assert.equal(afterRestart.find(lesson => lesson.id === 'restart-status')?.status, 'completed');
    assert.equal(afterRestart.find(lesson => lesson.id === 'restart-status')?.report?.teacherNotes, 'Saved to fallback mirror');
    console.log('✓ Restart reconciliation prefers the newer durable lesson status over a stale IndexedDB copy.');

    const initial: Lesson[] = [
      makeLesson('judy-0800', 'Judy', '08:00', 'completed'),
      makeLesson('kinda-0900', 'Kinda und Judy', '09:00', 'scheduled'),
      makeLesson('taleen-1000', 'Taleen Private', '10:00', 'scheduled'),
    ];
    const expectedAfterKinda = {
      'judy-0800': 'completed',
      'kinda-0900': 'completed',
      'taleen-1000': 'scheduled',
    };
    const expectedAfterTaleen = {
      'judy-0800': 'completed',
      'kinda-0900': 'completed',
      'taleen-1000': 'completed',
    };

    let fullState = initial;
    // This models the React state snapshot captured before the first completion
    // render has propagated. It deliberately remains stale across both writes.
    const staleHomeSnapshot = initial;

    await storage.setItem('dl_lessons', initial);
    await waitForLessonSyncQueue();

    const completeAndFlushStaleSnapshot = async (lessonId: string, expected: Record<string, string>) => {
      // Same shared completion mutation used by AppContext.saveLessonReport
      // when the actual Home checkmark handler completes a lesson.
      await enqueueLessonSyncTask(async () => {
        const mutation = applyLessonCompletionMutation(fullState, lessonId, lesson => ({
          ...lesson,
          status: 'completed',
          isAutoGenerated: false,
          report: { ...(lesson.report || {}), attendanceStatus: 'present' } as any,
          updatedAt: Date.now()
        } as Lesson));
        assert.equal(mutation.found, true, `${lessonId}: completion handler must find its target`);
        fullState = mutation.lessons;
        assertStatuses(fullState, expected, `${lessonId}: full state after completion mutation`);

        const pivot = fullState.find(lesson => lesson.id === lessonId)!;
        fullState = resequenceScheduledLessonsAfterChange(fullState, pivot);
        assertStatuses(fullState, expected, `${lessonId}: full state after resequence`);

        // Reproduce the real failure mode: a delayed callback can carry the old
        // scheduled Home projection. The persistence guard must retain completed IDs.
        const guarded = preserveCompletedLessonStatuses([fullState], staleHomeSnapshot);
        assertStatuses(guarded.lessons, expected, `${lessonId}: full state after stale-snapshot completion guard`);
        fullState = guarded.lessons;

        const deduplication = deduplicateLessonList(fullState);
        assert.deepEqual(Array.from(deduplication.removedIds), [], 'Judy, Kinda and Taleen are distinct lesson slots');
        fullState = deduplication.deduplicated as Lesson[];
        assertStatuses(fullState, expected, `${lessonId}: full state after deduplication`);

        await storage.setItem('dl_lessons', fullState);
      });
      await waitForLessonSyncQueue();

      assertStatuses(fullState, expected, `${lessonId}: full state immediately after updateFullLessonsStorage`);
      let persisted = (await storage.getItem<Lesson[]>('dl_lessons')) || [];
      assertStatuses(persisted, expected, `${lessonId}: persisted dl_lessons immediately after storage write`);

      // Same serialized queue and same merge helper used by AppContext.syncLessons.
      await enqueueLessonSyncTask(async () => {
        const merged = mergeLessonSyncSnapshot(persisted, staleHomeSnapshot);
        fullState = merged;
        await storage.setItem('dl_lessons', merged);
      });
      await waitForLessonSyncQueue();

      assertStatuses(fullState, expected, `${lessonId}: full state after syncLessons flush`);
      persisted = (await storage.getItem<Lesson[]>('dl_lessons')) || [];
      assertStatuses(persisted, expected, `${lessonId}: persisted dl_lessons after syncLessons flush`);

      // Simulate an app reload: no in-memory ref/state is reused.
      const reloaded = (await storage.getItem<Lesson[]>('dl_lessons')) || [];
      assertStatuses(reloaded, expected, `${lessonId}: state after reload`);
    };

    await completeAndFlushStaleSnapshot('kinda-0900', expectedAfterKinda);
    await completeAndFlushStaleSnapshot('taleen-1000', expectedAfterTaleen);

    const finalReload = (await storage.getItem<Lesson[]>('dl_lessons')) || [];
    assert.equal(finalReload.filter(lesson => lesson.status === 'completed').length, 3);
    console.log('✓ Same-day lesson completion persistence regression passed (Judy, Kinda und Judy, Taleen Private).');
  } finally {
    __setSimulatePrimaryDbForTests(false);
    if (originalLocalStorage === undefined) {
      delete (globalThis as any).localStorage;
    } else {
      (globalThis as any).localStorage = originalLocalStorage;
    }
  }
};

run().catch(error => {
  console.error('✗ Same-day lesson completion persistence regression failed:', error);
  process.exitCode = 1;
});
