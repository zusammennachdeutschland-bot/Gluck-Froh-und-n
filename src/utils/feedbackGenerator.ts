// ==========================================
// PICK HELPER
// ==========================================

function pick<T>(arr: T[], avoidIndex?: number): { item: T; index: number } {
  if (!arr || arr.length === 0) return { item: '' as any, index: -1 };
  let pool = arr;
  if (avoidIndex !== undefined && avoidIndex >= 0 && avoidIndex < arr.length && arr.length > 1) {
    pool = arr.filter((_, i) => i !== avoidIndex);
  }
  const randomIdx = Math.floor(Math.random() * pool.length);
  const chosen = pool[randomIdx];
  return { item: chosen, index: arr.indexOf(chosen) };
}

// ==========================================
// GENERATOR FUNCTION
// ==========================================

export const generateFeedback = (
  performance: StudentSessionPerformance,
  language: 'ar' | 'en' | 'de' = 'ar',
  avoidVariantId?: string,
  gender: 'male' | 'female' = performance.gender || 'male'
): { feedback: { short: string; parent: string; detailed: string }; variantId: string } => {
  const prevIndices = avoidVariantId ? avoidVariantId.split('-').map(Number) : [];

  let bases: Record<string, string[]>;
  let parts: Record<string, string[]>;
  let unders: Record<string, string[]>;
  let speaks: Record<string, string[]>;
  let reads: Record<string, string[]>;
  let writes: Record<string, string[]>;
  let focus: Record<string, string[]>;
  let progs: Record<string, string[]>;
  let openers: string[] = [];
  let closers: Record<string, string[]> = {};

  if (language === 'de') {
    bases = germanBase;
    parts = germanParticipation;
    unders = germanUnderstanding;
    speaks = germanSpeaking;
    reads = germanReading;
    writes = germanWriting;
    focus = germanFocus;
    progs = germanProgress;
  } else if (language === 'en') {
    bases = englishBase;
    parts = englishParticipation;
    unders = englishUnderstanding;
    speaks = englishSpeaking;
    reads = englishReading;
    writes = englishWriting;
    focus = englishFocus;
    progs = englishProgress;
  } else {
    // Authentic Egyptian Arabic: choose gender-specific dictionary
    if (gender === 'female') {
      bases = arabicBaseFemale;
      parts = arabicParticipationFemale;
      unders = arabicUnderstandingFemale;
      speaks = arabicSpeakingFemale;
      reads = arabicReadingFemale;
      writes = arabicWritingFemale;
      focus = arabicFocusFemale;
      progs = arabicProgressFemale;
      openers = arabicOpenersFemale;
      closers = arabicClosersFemale;
    } else {
      bases = arabicBaseMale;
      parts = arabicParticipationMale;
      unders = arabicUnderstandingMale;
      speaks = arabicSpeakingMale;
      reads = arabicReadingMale;
      writes = arabicWritingMale;
      focus = arabicFocusMale;
      progs = arabicProgressMale;
      openers = arabicOpenersMale;
      closers = arabicClosersMale;
    }
  }

  const currentLevel = performance.level || 'good';
  const baseOpts = bases[currentLevel] || [];
  const partOpts = performance.participation ? parts[performance.participation] || [] : [];
  const underOpts = performance.understanding ? unders[performance.understanding] || [] : [];
  const speakOpts = performance.speaking ? speaks[performance.speaking] || [] : [];
  const readOpts = performance.reading ? reads[performance.reading] || [] : [];
  const writeOpts = performance.writing ? writes[performance.writing] || [] : [];
  const focusOpts = performance.focus ? focus[performance.focus] || [] : [];
  const progOpts = performance.progress ? progs[performance.progress] || [] : [];
  const closeOpts = closers[currentLevel] || [];

  const op = pick(openers, prevIndices[0]);
  const b = pick(baseOpts, prevIndices[1]);
  const p = pick(partOpts, prevIndices[2]);
  const u = pick(underOpts, prevIndices[3]);
  const s = pick(speakOpts, prevIndices[4]);
  const r = pick(readOpts, prevIndices[5]);
  const w = pick(writeOpts, prevIndices[6]);
  const f = pick(focusOpts, prevIndices[7]);
  const pr = pick(progOpts, prevIndices[8]);
  const cl = pick(closeOpts, prevIndices[9]);

  const newVariantId = `${op.index}-${b.index}-${p.index}-${u.index}-${s.index}-${r.index}-${w.index}-${f.index}-${pr.index}-${cl.index}`;

  const coreBodyParts: string[] = [];
  if (b.item) coreBodyParts.push(b.item);
  if (p.item) coreBodyParts.push(p.item);
  if (u.item) coreBodyParts.push(u.item);
  if (s.item) coreBodyParts.push(s.item);
  if (r.item) coreBodyParts.push(r.item);
  if (w.item) coreBodyParts.push(w.item);

  let bodyText = coreBodyParts.join(language === 'ar' ? '، ' : ' ');
  
  if (pr.item) {
    bodyText += (bodyText ? (language === 'ar' ? '، ' : ' ') : '') + pr.item;
  }

  let parentText = '';
  if (language === 'ar') {
    // Natural Egyptian Teacher Message Structure
    const hasDetailedSkills = Boolean(p.item || u.item || s.item || r.item || w.item);
    if (hasDetailedSkills) {
      parentText = `${bodyText}.`;
    } else {
      parentText = `${b.item}.`;
    }

    if (cl.item) {
      parentText += `\n${cl.item}`;
    }
  } else {
    parentText = bodyText ? `${bodyText}.` : '';
  }

  let detailedText = parentText;
  if (f.item) {
    detailedText += (detailedText ? ' ' : '') + f.item;
  }

  let shortText = '';
  if (language === 'ar') {
    const levelLabel =
      performance.level === 'excellent'
        ? (gender === 'female' ? 'ممتازة وشاطرة جداً' : 'ممتاز وشاطر جداً')
        : performance.level === 'very_good'
        ? (gender === 'female' ? 'شغالة كويس جداً' : 'شغال كويس جداً')
        : performance.level === 'good'
        ? (gender === 'female' ? 'ماشية تمام ومستواها طيب' : 'ماشي تمام ومستواه طيب')
        : (gender === 'female' ? 'محتاجة شوية تدريب' : 'محتاج شوية تدريب');
    shortText = `أداء ${levelLabel} في حصة النهارده. 👍`;
  } else if (language === 'de') {
    shortText = `Heute eine ${
      performance.level === 'excellent'
        ? 'hervorragende'
        : performance.level === 'very_good'
        ? 'sehr gute'
        : performance.level === 'good'
        ? 'gute'
        : 'entwicklungsfähige'
    } Leistung! 👍`;
  } else {
    shortText = `${
      performance.level === 'excellent'
        ? 'Excellent'
        : performance.level === 'very_good'
        ? 'Very good'
        : performance.level === 'good'
        ? 'Good'
        : 'Developing'
    } performance today! 👍`;
  }

  return {
    feedback: {
      short: shortText,
      parent: parentText.trim(),
      detailed: detailedText.trim()
    },
    variantId: newVariantId
  };
};
