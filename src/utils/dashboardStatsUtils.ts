export interface DateRangeResult {
  startDateStr: string;
  endDateStr: string;
  startDate: Date;
  endDate: Date;
}

export interface DashboardPeriodStats {
  completed: number;
  cancelled: number;
  remaining: number;
  total: number;
}

export interface DashboardTodaySummary {
  visibleLessons: Lesson[];
  activeLessons: Lesson[];
  lessonsCount: number;
  studentsCount: number;
  completedCount: number;
  cancelledCount: number;
  remainingCount: number;
  percentDone: number;
  firstLessonTime: string | null;
}

/**
 * Computes Friday-to-Thursday week range containing `referenceDate`.
 */
export const getWeekDateRangeFridayToThursday = (referenceDate: Date | string): DateRangeResult => {
  const base = typeof referenceDate === 'string'
    ? parseLocalDate(normalizeDateToISO(referenceDate))
    : new Date(referenceDate);
  const day = base.getDay(); // 0=Sun, ..., 5=Fri, 6=Sat
  const daysSinceFriday = (day + 2) % 7;

  const friday = new Date(base);
  friday.setDate(base.getDate() - daysSinceFriday);
  friday.setHours(0, 0, 0, 0);

  const thursday = new Date(friday);
  thursday.setDate(friday.getDate() + 6);
  thursday.setHours(23, 59, 59, 999);

  return {
    startDateStr: formatLocalDate(friday),
    endDateStr: formatLocalDate(thursday),
    startDate: friday,
    endDate: thursday,
  };
};

/**
 * Computes 1st-to-last-day month range containing `referenceDate`.
 */
export const getMonthDateRange = (referenceDate: Date | string): DateRangeResult & { monthPrefix: string } => {
  const base = typeof referenceDate === 'string'
    ? parseLocalDate(normalizeDateToISO(referenceDate))
    : new Date(referenceDate);

  const firstDay = new Date(base.getFullYear(), base.getMonth(), 1);
  firstDay.setHours(0, 0, 0, 0);

  const lastDay = new Date(base.getFullYear(), base.getMonth() + 1, 0);
  lastDay.setHours(23, 59, 59, 999);

  const startDateStr = formatLocalDate(firstDay);
  const endDateStr = formatLocalDate(lastDay);

  return {
    startDateStr,
    endDateStr,
    startDate: firstDay,
    endDate: lastDay,
    monthPrefix: startDateStr.slice(0, 7),
  };
};

export const getLessonCanonicalSlotKey = (lesson: Partial<Lesson>): string => {
  const dateIso = normalizeDateToISO(lesson.date || '');
  const timeNorm = normalizeTime(lesson.time || '') || '00:00';
  if (lesson.groupId && lesson.groupId !== 'quick_group') {
    return `group:${lesson.groupId}:${dateIso}:${timeNorm}`;
  }
  return `id:${lesson.id || `${dateIso}_${timeNorm}`}`;
};

const isSyntheticProjectedLesson = (lesson: Partial<Lesson>): boolean => {
  const id = String(lesson.id || '');
  return /^l_auto_.+_\d{4}-\d{2}-\d{2}_\d{4}$/.test(id) && lesson.isAutoGenerated !== false;
};

const getRangeDedupePriority = (lesson: Partial<Lesson>): number => {
  const isSynthetic = isSyntheticProjectedLesson(lesson);
  if (lesson.status === 'completed') return isSynthetic ? 5 : 6;
  if (lesson.status === 'cancelled') return isSynthetic ? 4 : 5;
  if (lesson.status === 'in_progress') return isSynthetic ? 3 : 4;
  if (lesson.status === 'pending_action') return isSynthetic ? 2 : 3;
  return isSynthetic ? 1 : 2;
};

/**
 * Unified dashboard range lesson query for Weekly (Fri–Thu) and Monthly overviews.
 * - Includes explicit non-deleted stored lessons across [startDateStr, endDateStr].
 * - Projects recurring group occurrences ONLY for dates >= todayStr (no retroactive projection for past days).
 * - Deduplicates by canonical group+date+time slot (or lesson ID for private/quick lessons), ensuring explicit records win.
 */
export const getDashboardLessonsForRange = (params: {
  startDateStr: string;
  endDateStr: string;
  todayStr: string;
  lessons: Lesson[];
  groups: Group[];
  groupWeeklySessions?: GroupWeeklySession[];
}): Lesson[] => {
  const startIso = normalizeDateToISO(params.startDateStr);
  const endIso = normalizeDateToISO(params.endDateStr);
  const todayIso = normalizeDateToISO(params.todayStr);

  if (!startIso || !endIso || startIso > endIso) return [];

  const sourceLessons = Array.isArray(params.lessons) ? params.lessons : [];
  const activeGroups = Array.isArray(params.groups) ? params.groups : [];
  const weeklySessions = Array.isArray(params.groupWeeklySessions) ? params.groupWeeklySessions : [];
  const groupsById = new Map<string, Group>();
  activeGroups.forEach(g => {
    if (g?.id) groupsById.set(g.id, g);
  });

  // 1. Track soft-deleted slot keys (normalized time) & explicit stored lessons in [startIso, endIso]
  const deletedSlotKeys = new Set<string>();
  const explicitInRange = sourceLessons.filter(l => {
    if (!l || !l.date) return false;
    if (l.deleted) {
      if (l.groupId && l.groupId !== 'quick_group' && l.time) {
        deletedSlotKeys.add(getLessonCanonicalSlotKey(l));
      }
      return false;
    }
    const dateIso = normalizeDateToISO(l.date);
    return Boolean(dateIso && dateIso >= startIso && dateIso <= endIso);
  });

  // 2. Projected lessons strictly for >= todayIso
  const projectionStart = todayIso && todayIso > startIso ? todayIso : startIso;
  let projectedTodayAndFuture: Lesson[] = [];
  if (projectionStart <= endIso && (!todayIso || endIso >= todayIso)) {
    const projectedRaw = getProjectedLessonsForRange(
      projectionStart,
      endIso,
      activeGroups,
      sourceLessons,
      undefined,
      weeklySessions,
      sourceLessons
    );
    projectedTodayAndFuture = projectedRaw.filter(l => {
      if (!l || l.deleted) return false;
      const dateIso = normalizeDateToISO(l.date || '');
      if (!dateIso || dateIso < projectionStart || dateIso > endIso) return false;
      if (todayIso && dateIso < todayIso && isSyntheticProjectedLesson(l)) return false;
      if (deletedSlotKeys.has(getLessonCanonicalSlotKey(l))) return false;
      return true;
    });
  }

  // 3. Merge & deduplicate by canonical slot
  const bySlot = new Map<string, Lesson>();
  const consider = (candidate: Lesson) => {
    const grp = candidate.groupId ? groupsById.get(candidate.groupId) : undefined;
    if (!isLessonCompatibleWithGroupSchedule(candidate, grp)) return;

    const key = getLessonCanonicalSlotKey(candidate);
    const existing = bySlot.get(key);
    if (!existing) {
      bySlot.set(key, candidate);
      return;
    }

    const candPriority = getRangeDedupePriority(candidate);
    const existingPriority = getRangeDedupePriority(existing);
    if (
      candPriority > existingPriority ||
      (candPriority === existingPriority &&
        Number(candidate.updatedAt || 0) > Number(existing.updatedAt || 0))
    ) {
      bySlot.set(key, candidate);
    }
  };

  explicitInRange.forEach(consider);
  projectedTodayAndFuture.forEach(consider);

  return Array.from(bySlot.values()).sort((a, b) => {
    const dateCmp = normalizeDateToISO(a.date || '').localeCompare(normalizeDateToISO(b.date || ''));
    if (dateCmp !== 0) return dateCmp;
    return normalizeTime(a.time).localeCompare(normalizeTime(b.time));
  });
};

export const computeDashboardPeriodStats = (
  rangeLessons: Lesson[]
): DashboardPeriodStats => {
  let completed = 0;
  let cancelled = 0;
  let remaining = 0;

  for (const lesson of rangeLessons || []) {
    if (!lesson || lesson.deleted) continue;
    if (lesson.status === 'completed') {
      completed++;
    } else if (lesson.status === 'cancelled') {
      cancelled++;
    } else if (isPendingStatus(lesson.status)) {
      remaining++;
    }
  }

  return {
    completed,
    cancelled,
    remaining,
    total: (rangeLessons || []).filter(l => l && !l.deleted).length,
  };
};

/**
 * Counts unique active students attending a given list of lessons.
 * - Filters out deleted/archived students
 * - Applies `isStudentMatchingLessonWeek` so biweekly off-week students are never counted
 * - Returns 0 when there are no active lessons (never falls back to total roster size)
 */
export const countUniqueStudentsForLessons = (
  targetLessons: Lesson[],
  groups: Group[],
  students: Student[]
): number => {
  const activeStudents = (students || []).filter(s => !s.deleted && s.status !== 'archived');
  const studentsById = new Map<string, Student>();
  activeStudents.forEach(s => {
    if (s.id) studentsById.set(s.id, s);
  });

  const groupsById = new Map<string, Group>();
  (groups || []).forEach(g => {
    if (g?.id) groupsById.set(g.id, g);
  });

  const uniqueStudentKeys = new Set<string>();

  for (const lesson of targetLessons || []) {
    if (!lesson || lesson.deleted || lesson.status === 'cancelled') continue;

    if (lesson.studentId) {
      const st = studentsById.get(lesson.studentId);
      if (st) {
        if (!lesson.date || isStudentMatchingLessonWeek(st.scheduleRecurrence, lesson.date)) {
          uniqueStudentKeys.add(`id:${st.id}`);
        }
      } else {
        const anyMatch = (students || []).find(s => s.id === lesson.studentId);
        if (!anyMatch || (!anyMatch.deleted && anyMatch.status !== 'archived')) {
          uniqueStudentKeys.add(`id:${lesson.studentId}`);
        }
      }
      continue;
    }

    if (lesson.groupId && lesson.groupId !== 'quick_group') {
      const targetGroup = groupsById.get(lesson.groupId);
      const groupId = targetGroup ? targetGroup.id : lesson.groupId;
      const groupStudents = activeStudents.filter(s => s.groupId === groupId);
      groupStudents.forEach(s => {
        if (!lesson.date || isStudentMatchingLessonWeek(s.scheduleRecurrence, lesson.date)) {
          uniqueStudentKeys.add(`id:${s.id}`);
        }
      });
      continue;
    }

    if (lesson.studentName && lesson.studentName.trim()) {
      uniqueStudentKeys.add(`name:${lesson.studentName.trim().toLowerCase()}`);
    }
  }

  return uniqueStudentKeys.size;
};

/**
 * Single source of truth for Today's Dashboard Lesson Count, Unique Student Count,
 * and Completion Progress shared identically across Header and SmartDailySummaryWidget.
 */
export const getDashboardTodaySummary = (params: {
  todayStr: string;
  lessons: Lesson[];
  groups: Group[];
  groupWeeklySessions?: GroupWeeklySession[];
  students: Student[];
  dismissedDashboardLessonIds?: string[];
}): DashboardTodaySummary => {
  const {
    todayStr,
    lessons,
    groups,
    groupWeeklySessions = [],
    students,
    dismissedDashboardLessonIds = [],
  } = params;

  const dismissedSet = new Set(dismissedDashboardLessonIds || []);
  const visibleLessons = getLessonsForDate(todayStr, lessons, groups, groupWeeklySessions)
    .filter(l => !dismissedSet.has(l.id));

  const activeLessons = visibleLessons.filter(l => l.status !== 'cancelled');
  const lessonsCount = activeLessons.length;
  const completedCount = activeLessons.filter(l => l.status === 'completed').length;
  const cancelledCount = visibleLessons.filter(l => l.status === 'cancelled').length;
  const remainingCount = activeLessons.filter(l => isPendingStatus(l.status)).length;

  const studentsCount = countUniqueStudentsForLessons(activeLessons, groups, students);
  const percentDone = lessonsCount > 0
    ? Math.round((completedCount / lessonsCount) * 100)
    : 0;

  return {
    visibleLessons,
    activeLessons,
    lessonsCount,
    studentsCount,
    completedCount,
    cancelledCount,
    remainingCount,
    percentDone,
    firstLessonTime: activeLessons[0]?.time || null,
  };
};
