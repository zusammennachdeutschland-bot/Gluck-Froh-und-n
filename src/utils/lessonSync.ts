/**
 * Merge the filtered React lesson projection into the authoritative full-history
 * snapshot without allowing an older UI snapshot to overwrite persisted records.
 * Existing IDs always keep the full-store version; active state may only add IDs
 * that are genuinely absent from full storage.
 */
import type { Lesson } from '../types';

export const mergeLessonSyncSnapshot = (
  fullLessons: Lesson[],
  activeLessons: Lesson[],
  prunedIds: Set<string> = new Set()
): Lesson[] => {
  const merged: Lesson[] = [];
  const seenIds = new Set<string>();

  for (const lesson of fullLessons || []) {
    if (!lesson?.id || prunedIds.has(lesson.id) || seenIds.has(lesson.id)) continue;
    seenIds.add(lesson.id);
    merged.push(lesson);
  }

  for (const lesson of activeLessons || []) {
    if (!lesson?.id || prunedIds.has(lesson.id) || seenIds.has(lesson.id)) continue;
    seenIds.add(lesson.id);
    merged.push(lesson);
  }

  return merged;
};

/**
 * Keep completed status monotonic for an existing lesson ID. Delayed UI projections
 * and sync snapshots may carry older scheduled/in-progress copies after completion.
 */
export const preserveCompletedLessonStatuses = (
  previousSnapshots: Lesson[][],
  nextLessons: Lesson[]
): { lessons: Lesson[]; protectedIds: Set<string> } => {
  const completedById = new Map<string, Lesson>();
  for (const snapshot of previousSnapshots || []) {
    for (const lesson of snapshot || []) {
      if (lesson?.id && !lesson.deleted && lesson.status === 'completed') {
        completedById.set(lesson.id, lesson);
      }
    }
  }

  const protectedIds = new Set<string>();
  const lessons = (nextLessons || []).map(lesson => {
    const completed = lesson?.id ? completedById.get(lesson.id) : undefined;
    if (!lesson || lesson.deleted || !completed || lesson.status === 'completed' || lesson.status === 'cancelled') {
      return lesson;
    }
    protectedIds.add(lesson.id);
    return {
      ...completed,
      ...lesson,
      status: 'completed',
      isAutoGenerated: false,
      report: lesson.report || completed.report,
      updatedAt: Math.max(Number(lesson.updatedAt) || 0, Number(completed.updatedAt) || 0)
    } as Lesson;
  });

  return { lessons, protectedIds };
};
