import { Group, GroupWeeklySession, Lesson } from '../types';
import { getDayNumber, getGroupScheduleSlots, getProjectedLessonsForRange, isDateMatchingGroupRecurrence } from './scheduleUtils';
import { normalizeDateToISO, parseLocalDate } from './timeUtils';
import { normalizeTime } from './lessonUtils';

/** Compare lesson dates using the app's canonical local YYYY-MM-DD representation. */
export const isLessonOnDate = (
  lesson: Pick<Lesson, 'date'> | null | undefined,
  dateKey: string
): boolean => normalizeDateToISO(lesson?.date || '') === normalizeDateToISO(dateKey);

const isUnmodifiedProjectedLesson = (lesson: Lesson): boolean => {
  const match = String(lesson.id || '').match(/^l_auto_.+_(\d{4}-\d{2}-\d{2})_(\d{4})$/);
  if (!match || lesson.isAutoGenerated === false) return false;

  const expectedTime = `${match[2].slice(0, 2)}:${match[2].slice(2, 4)}`;
  // A changed date or time means this projected row was explicitly rescheduled.
  return normalizeDateToISO(lesson.date) === match[1] && normalizeTime(lesson.time) === expectedTime;
};

/**
 * Only discard an untouched projected group row when its original schedule no longer
 * contains that slot. Stored/manual/rescheduled rows always win over projections.
 */
export const isLessonCompatibleWithGroupSchedule = (
  lesson: Lesson,
  group?: Group | null
): boolean => {
  if (
    !group ||
    group.deleted ||
    !lesson.groupId ||
    lesson.groupId === 'quick_group' ||
    lesson.status !== 'scheduled'
  ) return true;

  const report = lesson.report;
  const hasRecordedWork = Boolean(
    report?.attendanceStatus ||
    report?.teacherNotes ||
    report?.homeworkTitle ||
    report?.quizScore !== undefined ||
    (lesson.studentPayments && Object.keys(lesson.studentPayments).length > 0) ||
    (lesson.amountPaid && lesson.amountPaid > 0) ||
    lesson.notes?.trim() ||
    lesson.quickNotes?.trim() ||
    lesson.topic?.trim() ||
    lesson.whatWasTaught?.trim() ||
    lesson.homeworkTitle?.trim() ||
    lesson.homeworkDescription?.trim() ||
    (lesson as any).isRescheduled ||
    (lesson as any).rescheduledFromDate ||
    (lesson as any).manualOverride
  );
  if (hasRecordedWork || !isUnmodifiedProjectedLesson(lesson)) return true;

  const dateKey = normalizeDateToISO(lesson.date);
  const recurrence = group.scheduleRecurrence;
  if (
    recurrence &&
    recurrence !== 'weekly' &&
    !isDateMatchingGroupRecurrence(recurrence, dateKey)
  ) return false;

  const slots = getGroupScheduleSlots(group);
  if (slots.length === 0) return true;

  const weekday = parseLocalDate(dateKey).getDay();
  const lessonTime = normalizeTime(lesson.time);
  return slots.some(slot =>
    getDayNumber(slot.day) === weekday &&
    normalizeTime(slot.time) === lessonTime
  );
};


/** Canonical daily lesson query shared by dashboard widgets. */
export const getLessonsForDate = (
  dateInput: string,
  lessons: Lesson[],
  groups: Group[],
  groupWeeklySessions: GroupWeeklySession[] = []
): Lesson[] => {
  const dateKey = normalizeDateToISO(dateInput);
  if (!dateKey) return [];
  const source = Array.isArray(lessons) ? lessons : [];
  const projected = getProjectedLessonsForRange(dateKey, dateKey, groups || [], source, undefined, groupWeeklySessions, source);
  const priority = (lesson: Lesson): number => {
    if (lesson.status === 'completed' || lesson.status === 'cancelled') return 5;
    if (lesson.status === 'in_progress') return 4;
    if (lesson.status === 'scheduled') return 2;
    return 1;
  };
  const bySlot = new Map<string, Lesson>();
  projected.forEach(lesson => {
    if (lesson.deleted || !isLessonOnDate(lesson, dateKey)) return;
    const key = lesson.groupId && lesson.groupId !== 'quick_group'
      ? `${lesson.groupId}_${dateKey}_${normalizeTime(lesson.time)}`
      : lesson.id;
    const current = bySlot.get(key);
    if (!current || priority(lesson) > priority(current) ||
      (priority(lesson) === priority(current) && Number((lesson as any).updatedAt || 0) > Number((current as any).updatedAt || 0))) {
      bySlot.set(key, lesson);
    }
  });
  return Array.from(bySlot.values()).sort((a, b) => normalizeTime(a.time).localeCompare(normalizeTime(b.time)));
};
